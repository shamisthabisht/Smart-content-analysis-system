import os
import sys
import time
from datetime import datetime
from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

# Add parent directory to sys.path so we can import src modules
current_dir = os.path.dirname(os.path.abspath(__file__))
parent_dir = os.path.dirname(current_dir)
if parent_dir not in sys.path:
    sys.path.insert(0, parent_dir)

from src.inference.ai_detector_pipeline import AIDetector
from src.inference.grammar_pipeline import GrammarCorrector
from src.inference.service import ContentAnalysisService
from backend.schemas import (
    AIDetectionRequest,
    AIDetectionResponse,
    GrammarRequest,
    GrammarResponse,
    CombinedAnalysisRequest,
    CombinedAnalysisResponse,
    HealthResponse,
)

from datetime import datetime, timezone

# Global service container (singleton)
class ModelManager:
    service: Optional[ContentAnalysisService] = None
    ai_detector: Optional[AIDetector] = None
    grammar_corrector: Optional[GrammarCorrector] = None
    start_time: Optional[str] = None

    @classmethod
    def get_service(cls) -> ContentAnalysisService:
        if cls.service is None:
            print("Loading ContentAnalysisService models into memory...")
            cls.service = ContentAnalysisService()
            cls.ai_detector = cls.service.ai_detector
            cls.grammar_corrector = cls.service.grammar_corrector
            cls.start_time = datetime.now(timezone.utc).isoformat()
        return cls.service

models = ModelManager()

@asynccontextmanager
async def lifespan(app: FastAPI):
    # Startup: Preload ML models into memory
    print("==================================================")
    print("Initializing AI Content Analysis Backend Service...")
    print("==================================================")
    models.get_service()
    print("ML Models successfully loaded into memory and ready for inference.")
    yield
    # Shutdown
    print("Shutting down AI Content Analysis Backend Service...")

app = FastAPI(
    title="AI Content Analysis System API",
    description="Production REST API for AI Text Detection and Grammar Error Correction",
    version="1.0.0",
    lifespan=lifespan
)

# CORS configuration
origins = [
    "http://localhost:5173",
    "http://localhost:3000",
    "http://127.0.0.1:5173",
    "http://127.0.0.1:3000",
    "*"
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/api/health", response_model=HealthResponse, tags=["System"])
async def health_check():
    """Health check endpoint to verify backend status and model readiness."""
    service = models.get_service()
    ai_loaded = service.ai_detector is not None
    grammar_loaded = service.grammar_corrector is not None
    device = getattr(service.grammar_corrector, "device", "cpu") if grammar_loaded else "unknown"

    return HealthResponse(
        status="healthy" if (ai_loaded and grammar_loaded) else "degraded",
        version="1.0.0",
        ai_detector_loaded=ai_loaded,
        grammar_model_loaded=grammar_loaded,
        device=device,
        timestamp=datetime.now(timezone.utc).isoformat()
    )

@app.post("/api/analyze/ai-detection", response_model=AIDetectionResponse, tags=["Analysis"])
async def detect_ai_content(req: AIDetectionRequest):
    """
    Analyzes input text to determine whether it was written by a human or generated by AI.
    Returns probabilities, confidence scores, and categorical assessment.
    """
    service = models.get_service()
    if not service.ai_detector:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="AI Detection model is not initialized."
        )

    try:
        t0 = time.time()
        res = service.ai_detector.predict(req.text)
        res["execution_time_seconds"] = round(time.time() - t0, 4)
        return AIDetectionResponse(**res)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error executing AI detection: {str(e)}"
        )

@app.post("/api/analyze/grammar", response_model=GrammarResponse, tags=["Analysis"])
async def correct_grammar(req: GrammarRequest):
    """
    Detects and corrects grammatical, spelling, and phrasing errors in input text.
    Returns corrected text and detailed word-level diffs.
    """
    service = models.get_service()
    if not service.grammar_corrector:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Grammar Correction model is not initialized."
        )

    try:
        t0 = time.time()
        res = service.grammar_corrector.correct_text(req.text)
        res["execution_time_seconds"] = round(time.time() - t0, 4)
        return GrammarResponse(**res)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error executing grammar correction: {str(e)}"
        )

@app.post("/api/analyze/combined", response_model=CombinedAnalysisResponse, tags=["Analysis"])
async def combined_analysis(req: CombinedAnalysisRequest):
    """
    Runs unified analysis including text statistics, AI detection, and grammar correction.
    """
    service = models.get_service()
    if not service:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Content Analysis service is not initialized."
        )

    try:
        options = {
            "enable_ai_detection": req.enable_ai_detection,
            "enable_grammar": req.enable_grammar
        }
        res = service.analyze_content(req.text, options=options)
        return CombinedAnalysisResponse(**res)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error executing combined analysis: {str(e)}"
        )

if __name__ == "__main__":
    import uvicorn
    uvicorn.run("backend.main:app", host="0.0.0.0", port=8000, reload=False)
